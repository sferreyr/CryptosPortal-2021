namespace App\Entity;

use App\Repository\LangCategoriesRepository;
use Doctrine\Common\Collections\ArrayCollection;
use Doctrine\Common\Collections\Collection;
use Doctrine\ORM\Mapping as ORM;

/**
 * @ORM\Entity(repositoryClass=LangCategoriesRepository::class)
 */
class LangCategories
{
    /**
     * @ORM\Id
     * @ORM\GeneratedValue
     * @ORM\Column(type="integer")
     */
    private $id;

    /**
     * @ORM\Column(type="string", length=255)
     */
    private $name;

    
    //Una Caegoria puede tener Muchos Posts
     /**
     * @ORM\OneToMany(targetEntity="App\Entity\Posts", mappedBy="langcategories")
     */
    private $langposts;







    public function __construct()
    {
        $this->langposts = new ArrayCollection();
    }

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getName(): ?string
    {
        return $this->name;
    }

    public function setName(string $name): self
    {
        $this->name = $name;

        return $this;
    }

    /**
     * @return Collection|Posts[]
     */
    public function getLangposts(): Collection
    {
        return $this->langposts;
    }

    public function addLangpost(Posts $langpost): self
    {
        if (!$this->langposts->contains($langpost)) {
            $this->langposts[] = $langpost;
            $langpost->setLangcategories($this);
        }

        return $this;
    }

    public function removeLangpost(Posts $langpost): self
    {
        if ($this->langposts->contains($langpost)) {
            $this->langposts->removeElement($langpost);
            // set the owning side to null (unless already changed)
            if ($langpost->getLangcategories() === $this) {
                $langpost->setLangcategories(null);
            }
        }

        return $this;
    }
}

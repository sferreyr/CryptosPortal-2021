namespace App\Entity;

use App\Repository\CategoriesRepository;
use Doctrine\Common\Collections\ArrayCollection;
use Doctrine\Common\Collections\Collection;
use Doctrine\ORM\Mapping as ORM;

/**
 * @ORM\Entity(repositoryClass=CategoriesRepository::class)
 */
class Categories
{
    /**
     * @ORM\Id
     * @ORM\GeneratedValue
     * @ORM\Column(type="integer")
     */
    private $id;

    /**
     * @ORM\Column(type="string", length=255)
     */
    private $name;

    /**
     * @ORM\Column(type="string", length=255)
     */
    private $photo;


    //Una Caegoria puede tener Muchos Posts
     /**
     * @ORM\OneToMany(targetEntity="App\Entity\Posts", mappedBy="categories")
     */
    private $posts;

    
    //Una Caegoria puede tener Muchas comunidades
     /**
     * @ORM\OneToMany(targetEntity="App\Entity\Communities", mappedBy="categories")
     */
    private $communities;


    
    public function __construct()
    {
        $this->posts = new ArrayCollection();
        $this->communities = new ArrayCollection();
    }

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getName(): ?string
    {
        return $this->name;
    }

    public function setName(string $name): self
    {
        $this->name = $name;

        return $this;
    }

    public function getPhoto(): ?string
    {
        return $this->photo;
    }

    public function setPhoto(string $photo): self
    {
        $this->photo = $photo;

        return $this;
    }

    /**
     * @return Collection|Posts[]
     */
    public function getPosts(): Collection
    {
        return $this->posts;
    }

    public function addPost(Posts $post): self
    {
        if (!$this->posts->contains($post)) {
            $this->posts[] = $post;
            $post->setCategories($this);
        }

        return $this;
    }

    public function removePost(Posts $post): self
    {
        if ($this->posts->contains($post)) {
            $this->posts->removeElement($post);
            // set the owning side to null (unless already changed)
            if ($post->getCategories() === $this) {
                $post->setCategories(null);
            }
        }

        return $this;
    }

    /**
     * @return Collection|Communities[]
     */
    public function getCommunities(): Collection
    {
        return $this->communities;
    }

    public function addCommunity(Communities $community): self
    {
        if (!$this->communities->contains($community)) {
            $this->communities[] = $community;
            $community->setCategories($this);
        }

        return $this;
    }

    public function removeCommunity(Communities $community): self
    {
        if ($this->communities->removeElement($community)) {
            // set the owning side to null (unless already changed)
            if ($community->getCategories() === $this) {
                $community->setCategories(null);
            }
        }

        return $this;
    }
}

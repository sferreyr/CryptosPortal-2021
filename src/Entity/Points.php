namespace App\Entity;

use App\Repository\PointsRepository;
use Doctrine\ORM\Mapping as ORM;

/**
 * @ORM\Entity(repositoryClass=PointsRepository::class)
 */
class Points
{
    /**
     * @ORM\Id
     * @ORM\GeneratedValue
     * @ORM\Column(type="integer")
     */
    private $id;


    /**
     * @ORM\Column(type="integer")
     */
    private $points;

    //Muchos Points puede tener solo un Post
     /**
     * @ORM\ManyToOne(targetEntity="App\Entity\Posts", inversedBy="points")
     */
    private $post;

    


     //Muchos Points puede tener solo un usuario
     /**
     * @ORM\ManyToOne(targetEntity="App\Entity\User", inversedBy="Postpoints")
     */
    private $user;


    public function getId(): ?int
    {
        return $this->id;
    }

  
    public function getPost(): ?Posts
    {
        return $this->post;
    }

    public function setPost(?Posts $post): self
    {
        $this->post = $post;

        return $this;
    }

    public function getPoints(): ?int
    {
        return $this->points;
    }

    public function setPoints(int $points): self
    {
        $this->points = $points;

        return $this;
    }

    public function getUser(): ?User
    {
        return $this->user;
    }

    public function setUser(?User $user): self
    {
        $this->user = $user;

        return $this;
    }
}

namespace App\Entity;

use App\Repository\CommunitiesPostsRepository;
use Doctrine\ORM\Mapping as ORM;

/**
 * @ORM\Entity(repositoryClass=CommunitiesPostsRepository::class)
 */
class CommunitiesPosts
{
    /**
     * @ORM\Id
     * @ORM\GeneratedValue
     * @ORM\Column(type="integer")
     */
    private $id;

     //Muchos Posts puede haber en una categoria
    /**
     * @ORM\ManyToOne(targetEntity="App\Entity\Communities", inversedBy="posts")
   
     */
    private $community;

    /**
     * @ORM\Column(type="string", length=255)
     */
    private $title;

    /**
     * @ORM\Column(type="string", length=14000)
     */
    private $content;


    /**
     * @ORM\Column(type="integer")
     */
    private $totalLikes;

    /**
     * @ORM\Column(type="integer")
     */
    private $totalPoints;

     //muchos Post puede tener solo un usuario
    /**
     * @ORM\ManyToOne(targetEntity="App\Entity\User", inversedBy="communityPosts")
     * @ORM\JoinColumn(name="user_id", referencedColumnName="id",nullable=false )
     */
    private $user;

    /**
     * @ORM\Column(type="integer")
     */
    private $totalDislikes;

    /**
     * @ORM\Column(type="integer")
     */
    private $totalComments;


    /**
     * @ORM\Column(type="datetime")
     */
    private $createAt;

    /**
     * @ORM\Column(type="boolean")
     */
    private $isSticky;

    /**
     * @ORM\Column(type="boolean")
     */
    private $isFeatured;

    /**
     * @ORM\Column(type="string", length=255)
     */
    private $titleSlug;

    /**
     * @ORM\Column(type="string", length=255)
     */
    private $groupSlug;




    public function __construct()
    {
      
        $this->createAt = new \DateTime();
     //   $this->points = 0;
        $this->isFeatured = false;
        $this->isSticky = false;
        $this->totalLikes = 0;
        $this->totalPoints = 0;
        $this->totalDislikes = 0;
        $this->totalComments = 0;
        

    }






    public function getId(): ?int
    {
        return $this->id;
    }

    public function getTitle(): ?string
    {
        return $this->title;
    }

    public function setTitle(string $title): self
    {
        $this->title = $title;

        return $this;
    }

    public function getTotalLikes(): ?string
    {
        return $this->totalLikes;
    }

    public function setTotalLikes(string $totalLikes): self
    {
        $this->totalLikes = $totalLikes;

        return $this;
    }

    public function getTotalPoints(): ?int
    {
        return $this->totalPoints;
    }

    public function setTotalPoints(int $totalPoints): self
    {
        $this->totalPoints = $totalPoints;

        return $this;
    }

    public function getTotalDislikes(): ?int
    {
        return $this->totalDislikes;
    }

    public function setTotalDislikes(int $totalDislikes): self
    {
        $this->totalDislikes = $totalDislikes;

        return $this;
    }

    public function getTotalComments(): ?int
    {
        return $this->totalComments;
    }

    public function setTotalComments(int $totalComments): self
    {
        $this->totalComments = $totalComments;

        return $this;
    }

    public function getContent(): ?string
    {
        return $this->content;
    }

    public function setContent(string $content): self
    {
        $this->content = $content;

        return $this;
    }

    public function getCreateAt(): ?\DateTimeInterface
    {
        return $this->createAt;
    }

    public function setCreateAt(\DateTimeInterface $createAt): self
    {
        $this->createAt = $createAt;

        return $this;
    }

    public function getIsSticky(): ?bool
    {
        return $this->isSticky;
    }

    public function setIsSticky(bool $isSticky): self
    {
        $this->isSticky = $isSticky;

        return $this;
    }

    public function getIsFeatured(): ?bool
    {
        return $this->isFeatured;
    }

    public function setIsFeatured(bool $isFeatured): self
    {
        $this->isFeatured = $isFeatured;

        return $this;
    }

    public function getTitleSlug(): ?string
    {
        return $this->titleSlug;
    }

    public function setTitleSlug(string $titleSlug): self
    {
        $this->titleSlug = $titleSlug;

        return $this;
    }

    public function getGroupSlug(): ?string
    {
        return $this->groupSlug;
    }

    public function setGroupSlug(string $groupSlug): self
    {
        $this->groupSlug = $groupSlug;

        return $this;
    }

    public function getUser(): ?User
    {
        return $this->user;
    }

    public function setUser(?User $user): self
    {
        $this->user = $user;

        return $this;
    }

   

    public function getCommunity(): ?Communities
    {
        return $this->community;
    }

    public function setCommunity(?Communities $community): self
    {
        $this->community = $community;

        return $this;
    }
}

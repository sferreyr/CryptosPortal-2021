namespace App\Entity;

use App\Repository\NotificationsRepository;
use Doctrine\ORM\Mapping as ORM;

/**
 * @ORM\Entity(repositoryClass=NotificationsRepository::class)
 */
class Notifications
{
    /**
     * @ORM\Id
     * @ORM\GeneratedValue
     * @ORM\Column(type="integer")
     */
    private $id;


    //Muchas notificaciones pueden tener muchos usuarios
     /**
     * @ORM\ManyToOne(targetEntity="App\Entity\User", inversedBy="notificationsRecipient")
     */
    private $recipient;


    //Muchas notificaciones pueden tener muchos usuarios
     /**
     * @ORM\ManyToOne(targetEntity="App\Entity\User", inversedBy="notificationsSender")
     */
    private $sender;



    //Muchas notificaciones pueden tener muchos usuarios
     /**
     * @ORM\ManyToOne(targetEntity="App\Entity\NotificationsTypes", inversedBy="notificationsTypes")
     */
    private $types;


    /**
     * @ORM\Column(type="datetime")
     */
    private $senddatetime;

    /**
     * @ORM\Column(type="boolean")
     */
    private $status;

    /**
     * @ORM\Column(type="boolean")
     */
    private $deleted;

    
     /**
     * @ORM\Column(type="string", length=255)
     */
    private $postTitle;



    /**
     * @ORM\Column(type="string", length=255)
     */
    private $url;



    public function getId(): ?int
    {
        return $this->id;
    }

    public function getSenddatetime(): ?\DateTimeInterface
    {
        return $this->senddatetime;
    }

    public function setSenddatetime(\DateTimeInterface $senddatetime): self
    {
        $this->senddatetime = $senddatetime;

        return $this;
    }

    public function getStatus(): ?bool
    {
        return $this->status;
    }

    public function setStatus(bool $status): self
    {
        $this->status = $status;

        return $this;
    }

    public function getDeleted(): ?bool
    {
        return $this->deleted;
    }

    public function setDeleted(bool $deleted): self
    {
        $this->deleted = $deleted;

        return $this;
    }

    public function getRecipient(): ?User
    {
        return $this->recipient;
    }

    public function setRecipient(?User $recipient): self
    {
        $this->recipient = $recipient;

        return $this;
    }

    public function getSender(): ?User
    {
        return $this->sender;
    }

    public function setSender(?User $sender): self
    {
        $this->sender = $sender;

        return $this;
    }

    public function getTypes(): ?NotificationsTypes
    {
        return $this->types;
    }

    public function setTypes(?NotificationsTypes $types): self
    {
        $this->types = $types;

        return $this;
    }
    public function getUrl(): ?string
    {
        return $this->url;
    }

    public function setUrl(string $url): self
    {
        $this->url = $url;

        return $this;
    }

    public function getPostTitle(): ?string
    {
        return $this->postTitle;
    }

    public function setPostTitle(string $postTitle): self
    {
        $this->postTitle = $postTitle;

        return $this;
    }
}

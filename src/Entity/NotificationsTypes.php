namespace App\Entity;

use App\Repository\NotificationsTypesRepository;
use Doctrine\Common\Collections\ArrayCollection;
use Doctrine\Common\Collections\Collection;
use Doctrine\ORM\Mapping as ORM;

/**
 * @ORM\Entity(repositoryClass=NotificationsTypesRepository::class)
 */
class NotificationsTypes
{
    /**
     * @ORM\Id
     * @ORM\GeneratedValue
     * @ORM\Column(type="integer")
     */
    private $id;

    /**
     * @ORM\Column(type="string", length=255)
     */
    private $name;

    /**
     * @ORM\Column(type="string", length=255)
     */
    private $description;

     //Un Usuario puede tener muchas notificaciones
     /**
     * @ORM\OneToMany(targetEntity="App\Entity\Notifications", mappedBy="types")
     */
    private $notificationsTypes;

         //Un Usuario puede tener muchas notificaciones
     /**
     * @ORM\OneToMany(targetEntity="App\Entity\Messages", mappedBy="types")
     */
    private $messagesTypes;




    public function __construct()
    {
        $this->notificationsTypes = new ArrayCollection();
        $this->messagesTypes = new ArrayCollection();
    }


    

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getName(): ?string
    {
        return $this->name;
    }

    public function setName(string $name): self
    {
        $this->name = $name;

        return $this;
    }

    public function getDescription(): ?string
    {
        return $this->description;
    }

    public function setDescription(string $description): self
    {
        $this->description = $description;

        return $this;
    }

    /**
     * @return Collection|Notifications[]
     */
    public function getNotificationsTypes(): Collection
    {
        return $this->notificationsTypes;
    }

    public function addNotificationsType(Notifications $notificationsType): self
    {
        if (!$this->notificationsTypes->contains($notificationsType)) {
            $this->notificationsTypes[] = $notificationsType;
            $notificationsType->setTypes($this);
        }

        return $this;
    }

    public function removeNotificationsType(Notifications $notificationsType): self
    {
        if ($this->notificationsTypes->removeElement($notificationsType)) {
            // set the owning side to null (unless already changed)
            if ($notificationsType->getTypes() === $this) {
                $notificationsType->setTypes(null);
            }
        }

        return $this;
    }

    /**
     * @return Collection|Notifications[]
     */
    public function getMessagesTypes(): Collection
    {
        return $this->messagesTypes;
    }

    public function addMessagesType(Messages $messagesType): self
    {
        if (!$this->messagesTypes->contains($messagesType)) {
            $this->messagesTypes[] = $messagesType;
            $messagesType->setTypes($this);
        }

        return $this;
    }

    public function removeMessagesType(Messages $messagesType): self
    {
        if ($this->messagesTypes->removeElement($messagesType)) {
            // set the owning side to null (unless already changed)
            if ($messagesType->getTypes() === $this) {
                $messagesType->setTypes(null);
            }
        }

        return $this;
    }

  
}

namespace App\Entity;

use App\Repository\AvatarTitlesRepository;
use Doctrine\Common\Collections\ArrayCollection;
use Doctrine\Common\Collections\Collection;
use Doctrine\ORM\Mapping as ORM;

/**
 * @ORM\Entity(repositoryClass=AvatarTitlesRepository::class)
 */
class AvatarTitles
{
    /**
     * @ORM\Id
     * @ORM\GeneratedValue
     * @ORM\Column(type="integer")
     */
    private $id;

    /**
    * @ORM\OneToMany(targetEntity="App\Entity\User", mappedBy="avatartitle")
     */
    private $title;

      /**
     * @ORM\Column(type="string")
     */
    private $titleName;
    /**
     * @ORM\Column(type="integer")
     */
    private $reqPoints;

    public function __construct()
    {
        $this->title = new ArrayCollection();
    }

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getTitle(): ?string
    {
        return $this->title;
    }

    public function setTitle(string $title): self
    {
        $this->title = $title;

        return $this;
    }

    public function getReqPoints(): ?int
    {
        return $this->reqPoints;
    }

    public function setReqPoints(int $reqPoints): self
    {
        $this->reqPoints = $reqPoints;

        return $this;
    }

    public function getTitleName(): ?string
    {
        return $this->titleName;
    }

    public function setTitleName(string $titleName): self
    {
        $this->titleName = $titleName;

        return $this;
    }

    public function addTitle(User $title): self
    {
        if (!$this->title->contains($title)) {
            $this->title[] = $title;
            $title->setAvatartitle($this);
        }

        return $this;
    }

    public function removeTitle(User $title): self
    {
        if ($this->title->removeElement($title)) {
            // set the owning side to null (unless already changed)
            if ($title->getAvatartitle() === $this) {
                $title->setAvatartitle(null);
            }
        }

        return $this;
    }
}

namespace App\Entity;

use App\Repository\DisLikesRepository;
use Doctrine\ORM\Mapping as ORM;

/**
 * @ORM\Entity(repositoryClass=DisLikesRepository::class)
 */
class DisLikes
{
    /**
     * @ORM\Id
     * @ORM\GeneratedValue
     * @ORM\Column(type="integer")
     */
    private $id;

    /**
     * @ORM\Column(type="boolean")
     */
    private $isDisliked;


    //Muchos Likes puede tener solo un usuario
     /**
     * @ORM\ManyToOne(targetEntity="App\Entity\User", inversedBy="dislikes")
     */
    private $user;


    //Muchos Likes puede tener solo un Post
     /**
     * @ORM\ManyToOne(targetEntity="App\Entity\Posts", inversedBy="Dislikes")
     */
    private $post;


    public function getId(): ?int
    {
        return $this->id;
    }

    public function getIsDisliked(): ?bool
    {
        return $this->isDisliked;
    }

    public function setIsDisliked(bool $isDisliked): self
    {
        $this->isDisliked = $isDisliked;

        return $this;
    }

    public function getUser(): ?User
    {
        return $this->user;
    }

    public function setUser(?User $user): self
    {
        $this->user = $user;

        return $this;
    }

    public function getPost(): ?Posts
    {
        return $this->post;
    }

    public function setPost(?Posts $post): self
    {
        $this->post = $post;

        return $this;
    }
}

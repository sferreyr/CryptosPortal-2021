namespace App\Entity;

use App\Repository\CommunitiesRepository;
use Doctrine\Common\Collections\ArrayCollection;
use Doctrine\Common\Collections\Collection;
use Doctrine\ORM\Mapping as ORM;

/**
 * @ORM\Entity(repositoryClass=CommunitiesRepository::class)
 */
class Communities
{
    /**
     * @ORM\Id
     * @ORM\GeneratedValue
     * @ORM\Column(type="integer")
     */
    private $id;

    //Muchas comunidades puede haber en una categoria
    /**
     * @ORM\ManyToOne(targetEntity="App\Entity\Categories", inversedBy="communities")
     * @ORM\JoinColumn(name="categories_id", referencedColumnName="id",nullable=false)
     */
    private $categories;

    //Una Caegoria puede tener Muchos Posts
    /**
     * @ORM\OneToMany(targetEntity="App\Entity\CommunitiesPosts", mappedBy="community")
     */
    private $posts;

    //Un usuario puede ser dueño  de Muchas comunidades 
    /**
     * @ORM\ManyToOne(targetEntity="App\Entity\User", inversedBy="oWcommunity")
     */
    private $owner;

    /**
     * @ORM\Column(type="string", length=255)
     */
    private $name;

    /**
     * @ORM\Column(type="string", length=255)
     */
    private $description;

    /**
     * @ORM\Column(type="string", length=255)
     */
    private $banner;

    /**
     * @ORM\Column(type="string", length=255)
     */
    private $cryptoIcon;


    /**
     * @ORM\Column(type="integer")
     */
    private $articles;

    /**
     * @ORM\Column(type="integer")
     */
    private $reputation;

    /**
     * @ORM\Column(type="string", length=255)
     */
    private $url;

    /**
     * @ORM\Column(type="datetime")
     */
    private $createAt;

    /**
     * @ORM\Column(type="integer")
     */
    private $totalComments;

    /**
     * @ORM\Column(type="integer")
     */
    private $totalPosts;


    /**
     * @ORM\Column(type="integer")
     */
    private $totalMembers;


    public function __construct()
    {

        $this->createAt = new \DateTime();
        //   $this->points = 0;
        $this->reputation = 0;
        $this->articles = 0;
        $this->posts = new ArrayCollection();
    }

    public function getId(): ?int
    {
        return $this->id;
    }



    public function getName(): ?string
    {
        return $this->name;
    }

    public function setName(string $name): self
    {
        $this->name = $name;

        return $this;
    }

    public function getDescription(): ?string
    {
        return $this->description;
    }

    public function setDescription(string $description): self
    {
        $this->description = $description;

        return $this;
    }


    public function getArticles(): ?int
    {
        return $this->articles;
    }

    public function setArticles(int $articles): self
    {
        $this->articles = $articles;

        return $this;
    }

    public function getReputation(): ?int
    {
        return $this->reputation;
    }

    public function setReputation(int $reputation): self
    {
        $this->reputation = $reputation;

        return $this;
    }

    public function getUrl(): ?string
    {
        return $this->url;
    }

    public function setUrl(string $url): self
    {
        $this->url = $url;

        return $this;
    }

    public function getCreateAt(): ?\DateTimeInterface
    {
        return $this->createAt;
    }

    public function setCreateAt(\DateTimeInterface $createAt): self
    {
        $this->createAt = $createAt;

        return $this;
    }

    public function getOwnerId(): ?User
    {
        return $this->ownerId;
    }

    public function setOwnerId(?User $ownerId): self
    {
        $this->ownerId = $ownerId;

        return $this;
    }

    public function getOwner(): ?User
    {
        return $this->owner;
    }

    public function setOwner(?User $owner): self
    {
        $this->owner = $owner;

        return $this;
    }

    public function getCategories(): ?Categories
    {
        return $this->categories;
    }

    public function setCategories(?Categories $categories): self
    {
        $this->categories = $categories;

        return $this;
    }

    public function getBanner(): ?string
    {
        return $this->banner;
    }

    public function setBanner(string $banner): self
    {
        $this->banner = $banner;

        return $this;
    }

    public function getCryptoIcon(): ?string
    {
        return $this->cryptoIcon;
    }

    public function setCryptoIcon(string $cryptoIcon): self
    {
        $this->cryptoIcon = $cryptoIcon;

        return $this;
    }

    /**
     * @return Collection|CommunitiesPosts[]
     */
    public function getPosts(): Collection
    {
        return $this->posts;
    }

    public function addPost(CommunitiesPosts $post): self
    {
        if (!$this->posts->contains($post)) {
            $this->posts[] = $post;
            $post->setCommunity($this);
        }

        return $this;
    }

    public function removePost(CommunitiesPosts $post): self
    {
        if ($this->posts->removeElement($post)) {
            // set the owning side to null (unless already changed)
            if ($post->getCommunity() === $this) {
                $post->setCommunity(null);
            }
        }

        return $this;
    }

    public function getTotalComments(): ?int
    {
        return $this->totalComments;
    }

    public function setTotalComments(int $totalComments): self
    {
        $this->totalComments = $totalComments;

        return $this;
    }

    public function getTotalPosts(): ?int
    {
        return $this->totalPosts;
    }

    public function setTotalPosts(int $totalPosts): self
    {
        $this->totalPosts = $totalPosts;

        return $this;
    }

    public function getTotalMembers(): ?int
    {
        return $this->totalMembers;
    }

    public function setTotalMembers(int $totalMembers): self
    {
        $this->totalMembers = $totalMembers;

        return $this;
    }
}

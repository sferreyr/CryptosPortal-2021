namespace App\Entity;

use App\Repository\SubCategoriesRepository;
use Doctrine\ORM\Mapping as ORM;
use Doctrine\Common\Collections\ArrayCollection;
use Doctrine\Common\Collections\Collection;

/**
 * @ORM\Entity(repositoryClass=SubCategoriesRepository::class)
 */
class SubCategories
{
    /**
     * @ORM\Id
     * @ORM\GeneratedValue
     * @ORM\Column(type="integer",nullable=false)
     * 
     */
    private $id;

    /**
     * @ORM\Column(type="string", length=255)
     */
    private $name;

  

    /**
     * @ORM\Column(type="string", length=255)
     */
    private $icon;

    /**
     * @ORM\OneToMany(targetEntity="App\Entity\Posts", mappedBy="subcategories")
     */
    private $subposts;

    public function __construct()
    {
        $this->subposts = new ArrayCollection();
    }

    /**
     * @return Collection|Posts[]
     */
    public function getSubposts(): Collection
    {
        return $this->subposts;
    }

    public function addSubpost(Posts $subpost): self
    {
        if (!$this->subposts->contains($subpost)) {
            $this->subposts[] = $subpost;
            $subpost->setSubcategories($this);
        }

        return $this;
    }

    public function removeSubpost(Posts $subpost): self
    {
        if ($this->subposts->contains($subpost)) {
            $this->subposts->removeElement($subpost);
            // set the owning side to null (unless already changed)
            if ($subpost->getSubcategories() === $this) {
                $subpost->setSubcategories(null);
            }
        }

        return $this;
    }

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getName(): ?string
    {
        return $this->name;
    }

    public function setName(string $name): self
    {
        $this->name = $name;

        return $this;
    }

    
   

    public function getIcon(): ?string
    {
        return $this->icon;
    }

    public function setIcon(string $icon): self
    {
        $this->icon = $icon;

        return $this;
    }
}

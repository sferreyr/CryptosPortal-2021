namespace App\Entity;

use App\Repository\MessagesRepository;
use Doctrine\ORM\Mapping as ORM;

/**
 * @ORM\Entity(repositoryClass=MessagesRepository::class)
 */
class Messages
{
    /**
     * @ORM\Id
     * @ORM\GeneratedValue
     * @ORM\Column(type="integer")
     */
    private $id;

  
    /**
     * @ORM\Column(type="datetime")
     */
    private $senddatetime;

    /**
     * @ORM\Column(type="boolean")
     */
    private $isDeleted;

     /**
     * @ORM\Column(type="string", length=255)
     */
    private $subject;

    /**
     * @ORM\Column(type="string", length=255)
     */
    private $content;


     //Muchas notificaciones pueden tener muchos usuarios
     /**
     * @ORM\ManyToOne(targetEntity="App\Entity\User", inversedBy="messagesRecipient")
     */
    private $recipient;


    //Muchas notificaciones pueden tener muchos usuarios
     /**
     * @ORM\ManyToOne(targetEntity="App\Entity\User", inversedBy="messagesSender")
     */
    private $sender;



    //Muchas notificaciones pueden tener muchos usuarios
     /**
     * @ORM\ManyToOne(targetEntity="App\Entity\NotificationsTypes", inversedBy="messagesTypes")
     */
    private $types;


    

    /**
     * @ORM\Column(type="string", length=255)
     */
    private $url;











    public function getId(): ?int
    {
        return $this->id;
    }

   

    public function getIsDeleted(): ?bool
    {
        return $this->isDeleted;
    }

    public function setIsDeleted(bool $isDeleted): self
    {
        $this->isDeleted = $isDeleted;

        return $this;
    }

    public function getContent(): ?string
    {
        return $this->content;
    }

    public function setContent(string $content): self
    {
        $this->content = $content;

        return $this;
    }

    public function getRecipient(): ?User
    {
        return $this->recipient;
    }

    public function setRecipient(?User $recipient): self
    {
        $this->recipient = $recipient;

        return $this;
    }

    public function getSender(): ?User
    {
        return $this->sender;
    }

    public function setSender(?User $sender): self
    {
        $this->sender = $sender;

        return $this;
    }

    public function getTypes(): ?NotificationsTypes
    {
        return $this->types;
    }

    public function setTypes(?NotificationsTypes $types): self
    {
        $this->types = $types;

        return $this;
    }

    public function getSubject(): ?string
    {
        return $this->subject;
    }

    public function setSubject(string $subject): self
    {
        $this->subject = $subject;

        return $this;
    }

    public function getUrl(): ?string
    {
        return $this->url;
    }

    public function setUrl(string $url): self
    {
        $this->url = $url;

        return $this;
    }

    public function getSenddatetime(): ?\DateTimeInterface
    {
        return $this->senddatetime;
    }

    public function setSenddatetime(\DateTimeInterface $senddatetime): self
    {
        $this->senddatetime = $senddatetime;

        return $this;
    }


}

class UserRepository extends ServiceEntityRepository implements PasswordUpgraderInterface
{
    public function __construct(ManagerRegistry $registry)
    {
        parent::__construct($registry, User::class);
    }

    /**
     * Used to upgrade (rehash) the user's password automatically over time.
     */
    public function upgradePassword(UserInterface $user, string $newEncodedPassword): void
    {
        if (!$user instanceof User) {
            throw new UnsupportedUserException(sprintf('Instances of "%s" are not supported.', \get_class($user)));
        }

        $user->setPassword($newEncodedPassword);
        $this->_em->persist($user);
        $this->_em->flush();
    }





    //Buscar TopUsuarios para DashBoard ((topusers))
    public function TopUsers()
    {

        $MIN_TOPUSER = '50'; // 50 points for top tops list.

        return $this->createQueryBuilder('u')
            ->andWhere('u.points >= :points')
            ->setParameter('points', $MIN_TOPUSER)
            ->orderBy('u.points', 'DESC')
            ->setMaxResults(10)
            ->getQuery()
            ->getResult();
    }



    //Search if User exist in Database By Email
    public function CheckUserExistEmail($email)
    {

        return $this->createQueryBuilder('u')
            ->where('u.email LIKE :email')
            ->setParameter('email', '%' . addcslashes($email, '%_') . '%')
            ->getQuery()->getResult(); //Use Only result for test. Paginator need Query
    }
    //Search if User exist in Database By Nickname
    public function CheckUserExistNickname($nickname)
    {


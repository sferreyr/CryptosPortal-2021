class CommentsRepository extends ServiceEntityRepository
{
    public function __construct(ManagerRegistry $registry)
    {
        parent::__construct($registry, Comments::class);
    }



    //Buscar post para el index ((latestpost))
    public function Viewcomments($postid)
    {

        $qb = $this->createQueryBuilder('p')
            ->where('p.posts = :id')
           
            ->setParameter('id', $postid);
        return  $qb->getQuery();
    }



 //Buscar LATEST COMMENTS para DashBoard ((latestcomments))
 public function LatestsComments()
 {

    
    $MAX_RESULTS = '15'; //  Max Lists to render in DashBoard

    return $this->createQueryBuilder('c')
     
         ->andWhere('c.id >= 0')
        ->leftJoin('c.posts', 'p')
        ->orderBy('c.createAt', 'DESC')
        ->setMaxResults($MAX_RESULTS)
        ->getQuery()
        ->getResult();
 }


     //Buscar Top Post para DashBoard ((toppost))
     public function GetAllCommentsPost($id)
     {
 
        return $this->createQueryBuilder('l')
        ->andWhere('l.posts = :id')
        ->setParameter('id', $id)
        ->select('count(l.id)')
        ->getQuery()
        ->getSingleScalarResult();
     }






     //Buscar LATEST COMMENTS PROFILE DE USUARIO
 public function UserProfileLatestsComments($id)
 {

    $MAX_RESULTS = '15'; //  Max Lists to render in DashBoard

    return $this->createQueryBuilder('u')
     
         ->where('u.user = :id')
        ->setParameter('id', $id)
        ->leftJoin('u.posts', 'p')
        ->orderBy('u.createAt', 'DESC')
        ->setMaxResults($MAX_RESULTS)
        ->getQuery()
        ->getResult();
 }

    
   //Buscar TOTAL COMMENTS PROFILE DE USUARIO 
    public function UserProfileTotalComments($id)
    {
        return $this->createQueryBuilder('u')
        ->where('u.user = :id')
        ->setParameter('id', $id)
        ->select('count(u.id)')
        ->getQuery()
        ->getSingleScalarResult();;
    }


    
    

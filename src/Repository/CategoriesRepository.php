    //Buscar post para el index ((latestpost))
    public function SearchAllCategoriesPhoto()
    {
        return $this->getEntityManager()
            ->createQuery('
            SELECT category.photo FROM App:Categories category
            ')->getResult();
    }


    //TOTAL CRYPTOS para DashBoard ((totalcryptos))
    public function TotalCryptos()
    {

        return $this->createQueryBuilder('p')
            ->select('count(p.id)')
            ->getQuery()
            ->getSingleScalarResult();
    }

    //Buscar IDS y Nombre de categorias
    public function SearchDropCategory()
    {
        return $this->getEntityManager()
            ->createQuery('
            SELECT category.id, category.name  FROM App:Categories category ')->getResult();
           
    }

    
    //Buscar IDS y Nombre de categorias
    public function GetAllCategories()
    {
        return $this->getEntityManager()
            ->createQuery('

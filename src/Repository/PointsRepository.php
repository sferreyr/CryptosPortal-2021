    //Find into Likes table by Id
    public function FindbyPostId($id)
    {
        return $this->createQueryBuilder('p')
           
        ->andWhere('p.post = :id')
        ->setParameter('id', $id)
        ->getQuery()->getResult();
    }


    //Find into Points table By User
    public function FindbyUser($user)
    {  
        $qb = $this->createQueryBuilder('p')
        ->where('p.user = :user')
        ->setParameter('user', $user);
       return  $qb->getQuery()->getResult();
    }


    //Find into Likes table By TOTAL LIKES with SAME POST ID
    public function GetTotalLikes($id)
    {
        return $this->createQueryBuilder('p')
        ->andWhere('p.post = :id')
        ->setParameter('id', $id)
        ->select('count(p.id)')
        ->getQuery()
        ->getSingleScalarResult();

    }













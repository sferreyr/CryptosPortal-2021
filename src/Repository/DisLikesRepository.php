{
    public function __construct(ManagerRegistry $registry)
    {
        parent::__construct($registry, DisLikes::class);
    }





    //Find into Likes table by Id
    public function FindbyPostId($id)
    {
        return $this->createQueryBuilder('l')
           
        ->andWhere('l.post = :id')
        ->setParameter('id', $id)
        ->getQuery()->getResult();
    }


    //Find into Likes table By User
    public function FindbyUser($user)
    {
        return $this->createQueryBuilder('l')
           
        ->andWhere('l.user = :user')
        ->setParameter('user', $user)
        ->getQuery()->getResult();
    }


    //Find into Likes table By TOTAL DisLIKES with SAME POST ID
    public function GetTotalDisLikes($id)
    {
        return $this->createQueryBuilder('l')
        ->andWhere('l.post = :id')
        ->setParameter('id', $id)
        ->select('count(l.id)')
        ->getQuery()
        ->getSingleScalarResult();

    }















    //Buscar Top Post para DashBoard ((toppost))
    public function TopPostPoints()
    {

        $MIN_TOPPOST = '20'; // 20 points for top tops list.

        return $this->createQueryBuilder('p')
            ->andWhere('p.totalPoints >= :totalPoints')
            ->setParameter('totalPoints', $MIN_TOPPOST)
            ->orderBy('p.totalPoints', 'DESC')
            ->setMaxResults(10)
            ->getQuery()
            ->getResult();
    }

    
    //Buscar Top Post para DashBoard ((toppost))
    public function TotalPosts()
    {

        return $this->createQueryBuilder('p')

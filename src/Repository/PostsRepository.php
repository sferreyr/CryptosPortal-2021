    public function SearchAllPosts()
    {
  
         return $this->createQueryBuilder('p')
           
            ->Where('p.id >= 0')
            
            ->leftJoin('p.categories', 'c')
          ->leftJoin('p.subcategories', 'sc')
          ->andWhere('sc.id != 3') // ID Q&A CATEGORY. EXCLUDE.
            ->leftJoin('p.langcategories', 'lc')
            ->leftJoin('p.user', 'u')

           // ->orderBy('p.isSticky', 'DESC') // Show First Sticky posts
         
            ->addOrderBy('p.isSticky', 'DESC') //// Show First Sticky posts
            ->addOrderBy('p.isFeatured', 'DESC') //// Show First Featured posts
            ->addOrderBy('p.createAt', 'DESC') //// Show First Featured posts

  
         //   ->leftJoin('p.categories', 'c')
  

            ->getQuery();
    }


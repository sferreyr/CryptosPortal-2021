            /*IMPORTANTE: PARA LOGRAR QUE FILTRE LAS COMUNIDADES LO QUE SE HACE ES AGREGAR EL ALIAS
            EN ESTA FUNCION ES C Y EL LEFT JOIN Categories. LUEGO EN LA CONSULTA POR MEDIO DE LA URL (REQUEST/GET) SE LE ASIGA UN c.ID Que busca la comparacion en 

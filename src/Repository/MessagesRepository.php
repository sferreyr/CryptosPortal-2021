//Get Messages LISTS for user. /* my_profileM */  NOT COUNT!
//This Generate a list with all messages
public function GetUserMessages($userid)
{

    $qb = $this->createQueryBuilder('n')
      
    ->where('n.recipient = :id') // donde el que recibe es igual al ID que le damos
    ->andWhere('n.isDeleted = false') // Donde las notificaciones sean deleted false/ Si son eliminadas son TRUE y no deben existir
    ->andWhere('n.sender != :id') // Donde las notificaciones No sean del mismo autor
    ->addOrderBy('n.senddatetime', 'DESC') // Show First DateTime most recent
    ->setParameter('id', $userid);
    return  $qb->getQuery()->getResult();
}



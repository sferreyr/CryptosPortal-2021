public function GetmessagesUserInRoom($chatId, $UserId)
{

    $qb = $this->createQueryBuilder('n')
    ->Where('n.id = :idroom') // El Id del room tiene que ser igual al pasado
    ->andWhere('(n.recipient = :id OR n.sender = :id)')
   ->andWhere('n.types = 1') // SOLO SEA DE NOTIFICACION TIPO MENSAJE

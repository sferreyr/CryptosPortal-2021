     */
    //Messages Delete
    public function MesagessDelete(Request $request, SluggerInterface $slugger)
    {
        //Check for user logged in
        if (!$this->get('security.authorization_checker')->isGranted('IS_AUTHENTICATED_FULLY')) {
            throw $this->createAccessDeniedException();
        }

        if (!$this->isCsrfTokenValid('ajax_actions', $request->headers->get('X-CSRF-Token'))) {
            throw $this->createAccessDeniedException('Invalid CSRF token.');
        }
        //AJAX DELETE NOTIFICATIONS //
        if ($request->isXmlHttpRequest()) {
            $idtodeleted = $request->get("id"); //obtenido de ajax Primer valor de DATA(ALIAS: id) NOTIFICACION
            $User = new User();
            //Obtenemos el ID del USUARIO LOGUEADO ACTUAL!
            $User = $this->getUser();   //Obtengo todos los datos del Usuario actual conectado
            $UserId = $User->getId();
            // $notificacion = new Notifications(); // Creo la clase de notificaciones
            $Message = $this->getDoctrine()->getRepository(Messages::class)->find($idtodeleted); // Busca por el Id ChatRoom MEssages
            if (!$Message ||
                ((!$Message->getRecipient() || $Message->getRecipient()->getId() !== $UserId) &&
                 (!$Message->getSender() || $Message->getSender()->getId() !== $UserId))) {
                throw $this->createNotFoundException('Message does not exist.');
            }
            $Message->setIsDeleted(true);

            //Manejador de Entidades Envio notificacion a la DB
            $nt = $this->getDoctrine()->getManager();
            $nt->persist($Message);
            $nt->flush();
            // $this->addFlash("DelNotification", "Se elimino la notificacion");

            return new JsonResponse(['notification' => $idtodeleted]);
        }
    }











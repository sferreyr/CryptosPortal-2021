    /**
     * @Route("/myprofile/avatar", name="my_profileA")
     */
    public function Avatar(Request $request, SluggerInterface $slugger)
    {

        //Check for user logged in
        if (!$this->get('security.authorization_checker')->isGranted('IS_AUTHENTICATED_FULLY')) {
            throw $this->createAccessDeniedException();
        }

        $User = new User();
        $form = $this->createForm(MyProfileAvatarType::class, $User);
        $form->handleRequest($request);
        $ProfileDirectory = "uploads/profiles/";

        //Obtenemos el ID del USUARIO LOGUEADO ACTUAL!
        $User = $this->getUser();   //Obtengo todos los datos del Usuario actual conectado.

        $Avatar = $User->getAvatar();



        if ($form->isSubmitted() && $form->isValid()) {
            /** @var UploadedFile $brochureFile */
            $brochureFile = $form->get('avatar')->getData();

            // this condition is needed because the 'brochure' field is not required
            // so the PDF file must be processed only when a file is uploaded
            if ($brochureFile) {
                $originalFilename = pathinfo($brochureFile->getClientOriginalName(), PATHINFO_FILENAME);
                // this is needed to safely include the file name as part of the URL
                $safeFilename = $slugger->slug($originalFilename);
                $newFilename = $safeFilename . '-' . uniqid() . '.' . $brochureFile->guessExtension();

                // Move the file to the directory where brochures are stored
                try {
                    $brochureFile->move(
                        $this->getParameter('profiles_directory'),
                        $newFilename
                    );
                } catch (FileException $e) {
                    $this->addFlash('error', 'No se pudo guardar la imagen.');
                    return $this->redirectToRoute('my_profileA');
                }

                // updates the 'brochureFilename' property to store the PDF file name
                // instead of its contents
                $User->setAvatar($ProfileDirectory . $newFilename);

                //Manejador de Entidades
                $em = $this->getDoctrine()->getManager();
                $em->persist($User);
                $em->flush();

                $this->addFlash("success", "Perfil Actualizado con exito");
                return $this->redirectToRoute('my_profileA');
            }
            $this->addFlash("success", "No se pudo actualizar no hay contenido");
        }


        return $this->render('my_profile/avatar.html.twig', [
            'form' => $form->createView(),
            'avatar' => $Avatar,



        ]);
    }









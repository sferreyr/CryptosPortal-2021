            $QueryUser = $this->getDoctrine()->getRepository(Notifications::class)->GetUserNotifications($UserId);
            // $notificacion = new Notifications(); // Creo la clase de notificaciones
            $Notificacion = $this->getDoctrine()->getRepository(Notifications::class)->findOneBy(['id' => $idtodeleted, 'recipient' => $User]);
            if (!$Notificacion) {
                throw $this->createNotFoundException('Notification does not exist.');
            }
            $Notificacion->setDeleted(true);

            //Manejador de Entidades Envio notificacion a la DB
            $nt = $this->getDoctrine()->getManager();
            $nt->persist($Notificacion);
            $nt->flush();
            // $this->addFlash("DelNotification", "Se elimino la notificacion");

            return new JsonResponse(['notification' => $idtodeleted]);
        }

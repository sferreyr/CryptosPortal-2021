namespace App\Controller;

use App\Entity\Categories;
use Symfony\Bundle\FrameworkBundle\Controller\AbstractController;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Annotation\Route;

class GetcryptoThirdpartyController extends AbstractController
{
    /**
     * @Route("/getcrypto/thirdparty", name="getcrypto_thirdparty")
     */
    public function index(): Response
    {
        throw $this->createNotFoundException('Historical import utility is disabled.');

        $MAX_CRYPTOS_LIST = 400;








        /*                                            */
        /*                                            */
        /* FUNCTION FOR GET IDS AND NAME FROM CRYPTO  */
        /*                                            */
        /*                                            */
        $url = 'https://sandbox-api.coinmarketcap.com/v1/cryptocurrency/listings/latest';
        $parameters = [
            'start' => '1',
            'limit' => $MAX_CRYPTOS_LIST,
            'convert' => 'USD'
        ];

        $headers = [
            'Accepts: application/json',
            'X-CMC_PRO_API_KEY: REPLACE_WITH_YOUR_SANDBOX_KEY' //testAPI
        ];
        $qs = http_build_query($parameters); // query string encode the parameters
        $request = "{$url}?{$qs}"; // create the request URL


        $curl = curl_init(); // Get cURL resource
        // Set cURL options
        curl_setopt_array($curl, array(
            CURLOPT_URL => $request,            // set the request URL
            CURLOPT_HTTPHEADER => $headers,     // set the headers 
            CURLOPT_RETURNTRANSFER => 1         // ask for raw response instead of bool
        ));

        $response = curl_exec($curl); // Send the request, save the response


        $response = (json_decode($response, true)); // print json decoded response


        $CryptoNames = [];  // IMPORTANT VARIABLE
        $CMCCryptoIDS = [];


        for ($i = 0; $i < $MAX_CRYPTOS_LIST; $i++) {


            $NAMEresponse = ($response['data'][$i]['name']);
            $IDresponse = ($response['data'][$i]['id']);


            array_push($CryptoNames, $NAMEresponse);
            array_push($CMCCryptoIDS, $IDresponse);
        }

        // dump($CryptoNames);
        //dump($CMCCryptoIDS);



        curl_close($curl); // Close request





        /*                                   */
        /*                                   */
        /* FUNCTION FOR GET LOGOS FROM URLS  */
        /*                                   */
        /*                                   */


        $CMCURLCryptoLOGOS = [];

        // for ($i = 0; $i < 10; $i++) {
        foreach ($CMCCryptoIDS as $key => $value) {


            $url = 'https://sandbox-api.coinmarketcap.com/v1/cryptocurrency/info';
            $parameters = [
                'id' => $value,

            ];

            $headers = [
                'Accepts: application/json',
                'X-CMC_PRO_API_KEY: REPLACE_WITH_YOUR_SANDBOX_KEY' //testAPI
            ];
            $qs = http_build_query($parameters); // query string encode the parameters
            $request = "{$url}?{$qs}"; // create the request URL


            $curl = curl_init(); // Get cURL resource
            // Set cURL options
            curl_setopt_array($curl, array(
                CURLOPT_URL => $request,            // set the request URL
                CURLOPT_HTTPHEADER => $headers,     // set the headers 
                CURLOPT_RETURNTRANSFER => 1         // ask for raw response instead of bool
            ));

            $response = curl_exec($curl); // Send the request, save the response


            $response = (json_decode($response, true)); // print json decoded response

            $LOGOresponse = ($response['data'][$value]['logo']);
            array_push($CMCURLCryptoLOGOS, $LOGOresponse);

            curl_close($curl); // Close request

        }



        //SAVE IMGS IN FOLDER
        //Get the file



  
        for ($i = 0; $i < $MAX_CRYPTOS_LIST; $i++) {
            $url =  $CMCURLCryptoLOGOS[$i];
            $name = $CryptoNames[$i];


            $destination = "img/cryptos/" . $name . ".png";

            $fp = fopen($destination, 'w+');
            $ch = curl_init();
            curl_setopt($ch, CURLOPT_URL, $url);
            curl_setopt($ch, CURLOPT_BINARYTRANSFER, true);
            curl_setopt($ch, CURLOPT_RETURNTRANSFER, false);
            curl_setopt($ch, CURLOPT_SSL_VERIFYPEER, true);

            curl_setopt($ch, CURLOPT_CONNECTTIMEOUT, 10);
            curl_setopt($ch, CURLOPT_FILE, $fp);
            curl_exec($ch);
            curl_close($ch);
            fclose($fp);
        }

    





      
        $em = $this->getDoctrine()->getManager();

        
        foreach ($CryptoNames as $key => $name) {
            $newcategorie =  new Categories;
       
            $AddCryptoToDB = $em->getRepository(Categories::class)->findOneBy(['name' => $name]);
          
            $newcategorie->setName($name);
           $newcategorie->setPhoto("img/cryptos/" . $name . ".png");

         


            if( !$AddCryptoToDB ){ // If crypto NOT Exist  SAVE IN DATABASE


                //Manejador de Entidades
                 $em->persist($newcategorie);
                 $em->flush();


            }else{


            }
        
            


        }

  
        






        return $this->render('getcrypto_thirdparty/index.html.twig', [
            'controller_name' => 'GetcryptoThirdpartyController',
        ]);
    }
}

namespace App\Controller;

use App\Entity\DisLikes;
use App\Entity\Likes;
use App\Entity\Points;
use App\Entity\Posts;
use App\Entity\User;
use Doctrine\DBAL\LockMode;
use Symfony\Bundle\FrameworkBundle\Controller\AbstractController;
use Symfony\Component\HttpFoundation\JsonResponse;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\Routing\Annotation\Route;

class AjaxController extends AbstractController
{
    /** @Route("/like", options={"expose"=true}, name="likes", methods={"POST"}) */
    public function Like(Request $request)
    {
        return $this->vote($request, Likes::class, 'likes', 'AlreadyLike');
    }

    /** @Route("/dislikes", options={"expose"=true}, name="dislikes", methods={"POST"}) */
    public function DisLike(Request $request)
    {
        return $this->vote($request, DisLikes::class, 'dislikes', 'AlreadyDisLike');
    }

    private function checkRequest(Request $request): int
    {
        $this->denyAccessUnlessGranted('IS_AUTHENTICATED_FULLY');
        if (!$this->isCsrfTokenValid('ajax_actions', $request->headers->get('X-CSRF-Token'))) {
            throw $this->createAccessDeniedException('Invalid CSRF token.');
        }
        $id = filter_var($request->request->get('id'), FILTER_VALIDATE_INT, ['options' => ['min_range' => 1]]);
        if (false === $id) {
            throw $this->createNotFoundException('Post does not exist.');
        }
        return $id;
    }

    private function vote(Request $request, string $entity, string $key, string $duplicate): JsonResponse
    {
        $id = $this->checkRequest($request);
        $em = $this->getDoctrine()->getManager();
        $user = $this->getUser();

        return $em->transactional(function ($em) use ($id, $user, $entity, $key, $duplicate) {
            $post = $em->find(Posts::class, $id, LockMode::PESSIMISTIC_WRITE);
            if (!$post) {
                throw $this->createNotFoundException('Post does not exist.');
            }
            $em->refresh($post, LockMode::PESSIMISTIC_WRITE);
            if ($em->getRepository($entity)->findOneBy(['post' => $post, 'user' => $user])) {
                return new JsonResponse([$key => $duplicate]);
            }
            $vote = new $entity();
            $vote->setPost($post);
            $vote->setUser($user);
            if (Likes::class === $entity) {
                $vote->setIsLiked(true);
                $post->setTotalLikes($post->getTotalLikes() + 1);
                $total = $post->getTotalLikes();
            } else {
                $vote->setIsDisLiked(true);
                $post->setTotalDisLikes($post->getTotalDisLikes() + 1);
                $total = $post->getTotalDisLikes();
            }
            $em->persist($vote);
            return new JsonResponse([$key => $total]);
        });
    }

    /** @Route("/gpoints", options={"expose"=true}, name="gpoints", methods={"POST"}) */
    public function GivePoints(Request $request)
    {
        $id = $this->checkRequest($request);
        $amount = filter_var($request->request->get('cant'), FILTER_VALIDATE_INT,
            ['options' => ['min_range' => 1, 'max_range' => 10]]);
        if (false === $amount) {
            return new JsonResponse(['points' => 'ERROR'], 400);
        }
        $em = $this->getDoctrine()->getManager();
        $userId = $this->getUser()->getId();

        return $em->transactional(function ($em) use ($id, $userId, $amount) {
            // Reload the balance under a lock, including requests for different posts.
            $user = $em->find(User::class, $userId, LockMode::PESSIMISTIC_WRITE);
            $em->refresh($user, LockMode::PESSIMISTIC_WRITE);
            $post = $em->find(Posts::class, $id, LockMode::PESSIMISTIC_WRITE);
            if (!$post) {
                throw $this->createNotFoundException('Post does not exist.');
            }
            $em->refresh($post, LockMode::PESSIMISTIC_WRITE);
            if ($em->getRepository(Points::class)->findOneBy(['post' => $post, 'user' => $user])) {
                return new JsonResponse(['points' => 'AlreadyPoints']);
            }
            if ($amount > $user->getMaxPointsperDay()) {
                return new JsonResponse(['points' => 'ERROR'], 400);
            }
            $points = new Points();
            $points->setPoints($amount);
            $points->setPost($post);
            $points->setUser($user);
            $user->setMaxPointsperDay($user->getMaxPointsperDay() - $amount);
            $post->setTotalPoints($post->getTotalPoints() + $amount);
            $em->persist($points);
            return new JsonResponse(['points' => $post->getTotalPoints()]);
        });
    }
}

    /**
     * @Route("/NewCommunity", name="NewCommunity")
     */
    public function NewCommunity(Request $request, SluggerInterface $slugger): Response
    {

        //Check for user logged in
        if (!$this->get('security.authorization_checker')->isGranted('IS_AUTHENTICATED_FULLY')) {
            throw $this->createAccessDeniedException();
        }

        $ncommu = new Communities();
       
        $form = $this->createForm(NewCommunityType::class, $ncommu);
        $form->handleRequest($request);

        if ($form->isSubmitted() && $form->isValid()) {

            $user = $this->getUser();

            $name = $form["name"]->getData();
            $description = $form["description"]->getData();
            //Banner img 
            $BannersDirectory = "uploads/communities/banner/";
            $banner = $form["banner"]->getData();
            $bannerPath = 'img/misc/block.jpg';
            if ($banner) {
                $originalFilename = pathinfo($banner->getClientOriginalName(), PATHINFO_FILENAME);
                // this is needed to safely include the file name as part of the URL
                $safeFilename = $slugger->slug($originalFilename);
                $newFilename = $safeFilename . '-' . uniqid() . '.' . $banner->guessExtension();

                // Move the file to the directory where brochures are stored
                try {
                    $banner->move(
                        $this->getParameter('CommunityBanners_Directory'),
                        $newFilename
                    );
                } catch (FileException $e) {
                    $this->addFlash('error', 'No se pudo guardar la imagen.');
                    return $this->redirectToRoute('NewCommunity');
                }
            }

            if ($banner) {
                $bannerPath = $BannersDirectory . $newFilename;
            }
            //END BANNER IMG

        
            $url = 'asdsa';
            $cryptoCategory = $form["categories"]->getData();
            $cryptoIcon = $cryptoCategory->getPhoto();

            $ncommu->setCategories($cryptoCategory);
            $ncommu->setName($name);
            $ncommu->setDescription($description);
            $ncommu->setBanner($bannerPath);
            $ncommu->setCryptoIcon($cryptoIcon);
            $ncommu->setUrl($url);
            $ncommu->setOwner($user);


            //Manejador de Entidades
            $em = $this->getDoctrine()->getManager();
            $em->persist($ncommu);
            $em->flush();


            //dump($user);


        }








        return $this->render('communities/NewCommunity.html.twig', [
            'controller_name' => 'CommunitiesController',
            'ncommu' => $form->createView(),
        ]);
    }








    function  NewComment(AuthorizationCheckerInterface $authChecker, $postid, $Comment, $AuthorUser, $titleSlug, $categorySlug, $pagination)
    {
        //Check for user logged in
        if (!$this->get('security.authorization_checker')->isGranted('IS_AUTHENTICATED_FULLY')) {
            throw $this->createAccessDeniedException();
        }
        $IsuserOnline = $authChecker->isGranted('ROLE_USER');

        if ($IsuserOnline != null) { // Chequeo de usuarios si esta logueado.
            $em = $this->getDoctrine()->getManager();
            $user = $this->getUser();
            /* Hay que llamar a la base de datos nuevamente para recuperar completamente Posts para luego poder setear el Id del post al comentario. */
            $post = $this->getDoctrine()->getRepository(Posts::class)->find($postid);
            if (!$post) {
                throw $this->createNotFoundException('posts does not exist');
            }

            $Comment->setPosts($post);
            $Comment->setUser($user);
            //Obtenemos los comentarios y le sumamos este actual comentario
            $totalcomments = $post->getTotalComments();
            $post->setTotalComments($totalcomments + 1);


            //check for mention user
            // dump($Comment->getContent());
            $string =  $Comment->getContent();
            $matches = array();
            $pattern = "/@[a-zA-Z0-9]+/";

            preg_match_all($pattern, $string, $matches);




            //$notifier->send(new Notification('Tu comentario fue agregado correctamente.', ['browser'])); // Notificacion en el mismo POST MESSAGE
            //If Comment is Success
            $this->addFlash(
                'Content',
                'Tu comentario fue agregado correctamente.'
            );








            $notificacion = new Notifications(); // Creo la clase de notificaciones
            $queryNotificationsType = $em->getRepository(NotificationsTypes::class)->find(2); // Busca por el Id 2 que son los comentarios.
            //Creamos el objeto para poder hacer la notificacion
            $notificacion->setRecipient($AuthorUser);
            $notificacion->setSender($user);
            $notificacion->setTypes($queryNotificationsType);
            $notificacion->setsenddatetime(new \DateTime());
            $notificacion->setStatus(0);
            $notificacion->setPostTitle($titleSlug);
            $notificacion->setDeleted(false);


            // For get Comment ID we need send first the comment, and after notifications.
            //Manejador de Entidades
            $em = $this->getDoctrine()->getManager();
            $em->persist($Comment);
            $em->flush();



            // MENTIONS USER 
            foreach ($matches as $key => $value) {

                //Syntax fix
                // [ONLY ONE NAME FOR EACH USER]
                // [WHEN USER HAVE @, ', ; WE REMOVED THIS.]
                $UserMentioned = $value;
                $pattern = "/@[a-zA-Z0-9]+/";
                $result = array_unique(str_replace(array("@", "'", ";"), '', $UserMentioned));


                foreach ($result as $key => $value) {
                    $result = $value;

                    //We Need get User ID with Only name
                    $query = $this->getDoctrine()->getRepository(User::class)->GetUserIdbyName($result);

                    //Send Notification To Users MENTIONED.
                    $notificacion_mention = new Notifications(); // Creo la clase de notificaciones
                    $notificacion_mentionType = $em->getRepository(NotificationsTypes::class)->find(3); // Busca por el Id 3 que son los comentarios Respondidos.
                    //Creamos el objeto para poder hacer la notificacion
                    $notificacion_mention->setRecipient($query);
                    $notificacion_mention->setSender($user);
                    $notificacion_mention->setTypes($notificacion_mentionType);
                    $notificacion_mention->setsenddatetime(new \DateTime());
                    $notificacion_mention->setStatus(0);
                    $notificacion_mention->setPostTitle($titleSlug);
                    $notificacion_mention->setDeleted(false);
                      
                    $RecipientNotification = $notificacion_mention->getRecipient() ;
                    $SenderNotification = $notificacion_mention->getSender() ;




                    //Sanity check for page = 1
                    if ($pagination->getTotalItemCount() == 0) {
                        $pagination->setTotalItemCount(1);
                    }
                    //generate url for comment with #id
                    $urlgeneradaMention = $this->generateUrl('viewpost', array(
                        'ptitle' => $titleSlug,
                        'category' => $categorySlug,
                        'page' => (ceil($pagination->getTotalItemCount() / 15/*Limit per page */)),
                        '_fragment' => $Comment->getId(),

                    ));

                    //Now we set Url generated with page and comment id
                    $notificacion_mention->setUrl($urlgeneradaMention);

                    //Si el usuario que envia la notificacion es diferente al que la recibe, enviamos a la database.
                    if ($SenderNotification !==  $RecipientNotification) {
                        //Manejador de Entidades Envio notificacion a la DB
                        $nt2 = $this->getDoctrine()->getManager();
                        $nt2->persist($notificacion_mention);
                        $nt2->flush();
                    } else {
                        return null;
                    }





                    // dump($query);
                }
            }

            //Sanity check for page = 1
            if ($pagination->getTotalItemCount() == 0) {
                $pagination->setTotalItemCount(1);
            }
            $urlgenerada = $this->generateUrl('viewpost', array(
                'ptitle' => $titleSlug,
                'category' => $categorySlug,
                'page' => (ceil($pagination->getTotalItemCount() / 15/*Limit per page */)),
                '_fragment' => $Comment->getId(),

            ));

            //Now we set Url generated with page and comment id
            $notificacion->setUrl($urlgenerada);


            //Si el usuario que envia la notificacion es diferente al que la recibe, enviamos a la database.
            if ($notificacion->getSender() !==  $notificacion->getRecipient()) {
                //Manejador de Entidades Envio notificacion a la DB
                $nt = $this->getDoctrine()->getManager();
                $nt->persist($notificacion);
                $nt->flush();
            } else {
                return null;
            }
        }
        return true;
    }







  public function index(PaginatorInterface $paginator, Request $request)
  {
    $em = $this->getDoctrine()->getManager();
    $querypaginator = $em->getRepository(Posts::class)->SearchAllPosts();
    $querypaginator2 = $em->getRepository(Posts::class)->SearchAllPostsQyA();
    $queryTopPost = $em->getRepository(Posts::class)->TopPostPoints();

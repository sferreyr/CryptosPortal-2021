    /* Paginador del Index ((latestpost)) */
    $pagination = $paginator->paginate(
      $querypaginator, /* query NOT result */
      $request->query->getInt('page', 1,), /*page number*/
      25 /*limit per page*/
    );

    /* Paginador del Index ((latestpost)) Q&A */
    $pagination2 = $paginator->paginate(
      $querypaginator2, /* query NOT result */
      
      $request->query->getInt('pageBBB', 1,), /*page number*/
      25 /*limit per page*/, 
      array(
        'pageParameterName' => 'pageBBB',
      
    )
      
    );

    // Dropdown de categorias (CRYPTOS)
    $CryptoCats = new Categories();
    $formCategories = $this->createForm(CategoriesType::class, $CryptoCats);

    // Dropdown de SUB categorias (TEMATICAS) TOPIC
    $SubCryptoCats = new Categories();
    $formSubCategories = $this->createForm(SubCategoriesType::class, $SubCryptoCats);

    //Dropdown Language
    $Langcategories = new LangCategories();
    $formLanguage = $this->createForm(LanguageType::class, $Langcategories);

    // SearchBar
    $formSearchBar = $this->createForm(SearchBarType::class);
    $formSearchBar->handleRequest($request);
    if ($formSearchBar->isSubmitted() && $formSearchBar->isValid()) {
      //We get SearchBar component ARRAY.
      $UserInput =  $request->get("search_bar");
      //With trim and Strip we can prevent Sql Injection or similar.
      $Searchtxt = trim(strip_tags($UserInput['SearchBar']));

      //dump($Searchtxt);
      //implement your search here, 
      $QuerySearchBox = $this->getDoctrine()->getRepository(Posts::class)->SearchBox($Searchtxt);
      //dump($repository);

      // We Send Update to Paginator in Dashboard with result from Searchbox
      /* Paginador del Index ((latestpost)) */
      $pagination = $paginator->paginate(
        $QuerySearchBox, /* query NOT result */
        $request->query->getInt('page', 1), /*page number*/
        25 /*limit per page*/
      );
    }




    return $this->render('dashboard/index.html.twig', [
      'controller_name' => 'CryptosPortal.com',
      'pagination' => $pagination,
      'pagination2' => $pagination2,
      'toppost' => $queryTopPost,
      'topusers' => $queryTopUser,
      'latestcoments' => $queryLatestComments,
      'totalposts' => $queryTotalPost,
      'totalcryptos' => $queryTotalCryptos,
      // 'querytotallikes' =>$QueryTotalLikes,
      'categorydrop' => $formCategories->createView(),
      'subcategorydrop' => $formSubCategories->createView(),
      'Languagedrop' => $formLanguage->createView(),
      'SearchBar' => $formSearchBar->createView(),


    ]);
  }






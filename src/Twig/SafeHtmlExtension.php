namespace App\Twig;

use HTMLPurifier;
use HTMLPurifier_Config;
use Twig\Extension\AbstractExtension;
use Twig\TwigFilter;

/** Preserve basic editor formatting without trusting user HTML. */
class SafeHtmlExtension extends AbstractExtension
{
    private $purifier;

    public function __construct()
    {
        $config = HTMLPurifier_Config::createDefault();
        $config->set('Core.Encoding', 'UTF-8');
        $config->set('HTML.Allowed', 'p,br,strong,b,em,i,u,ul,ol,li,blockquote,pre,code,a[href|title],h2,h3,h4');
        $config->set('URI.AllowedSchemes', ['http' => true, 'https' => true, 'mailto' => true]);
        $config->set('Cache.DefinitionImpl', null);
        $this->purifier = new HTMLPurifier($config);
    }

    public function getFilters(): array
    {
        return [new TwigFilter('safe_html', [$this, 'sanitize'], ['is_safe' => ['html']])];
    }

    public function sanitize(?string $html): string
    {
        return $this->purifier->purify($html ?? '');
    }
}

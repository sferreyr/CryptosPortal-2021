namespace App\Form;

use App\Entity\Categories;
use App\Entity\LangCategories;
use App\Entity\Posts;
use App\Entity\SubCategories;
use App\Entity\User;

use Doctrine\ORM\EntityRepository;
use FOS\CKEditorBundle\Form\Type\CKEditorType;
use Symfony\Bridge\Doctrine\Form\Type\EntityType;
use Symfony\Component\Form\AbstractType;
use Symfony\Component\Form\Extension\Core\Type\ChoiceType;
use Symfony\Component\Form\Extension\Core\Type\SubmitType;
use Symfony\Component\Form\Extension\Core\Type\TextType;
use Symfony\Component\Form\FormBuilderInterface;
use Symfony\Component\OptionsResolver\OptionsResolver;
use Beelab\Recaptcha2Bundle\Form\Type\RecaptchaType;
use Beelab\Recaptcha2Bundle\Validator\Constraints\Recaptcha2;



class PostsType extends AbstractType
{
    public function buildForm(FormBuilderInterface $builder, array $options)
    { 
        
    
       
        //var_dump($options);

       
        $builder
        
            ->add('title')
            //Categorias Bitcoin,Eth, Etc.
            ->add('categories', EntityType::class, [
                'class' => Categories::class,
                'query_builder' => function (EntityRepository $er) {
                    return $er->createQueryBuilder('u')
                        ->orderBy('u.name', 'ASC');
                },
                'choice_label' => 'name',
                'choice_value' => 'name',
            ])
            //Categorias De Idioma
            ->add('langcategories', EntityType::class, [
                'class' => LangCategories::class,
                'query_builder' => function (EntityRepository $er) {
                    return $er->createQueryBuilder('u')
                        ->orderBy('u.name', 'ASC');
                },
                'choice_label' => 'name',
                'choice_value' => 'name',
            ])
            //Categorias de Tematica
            ->add('subcategories', EntityType::class, [
                'class' => SubCategories::class,
                'query_builder' => function (EntityRepository $er) {
                    return $er->createQueryBuilder('u')
                        ->orderBy('u.name', 'ASC');
                },
                'choice_label' => 'name',
            ])


            ->add('captcha', RecaptchaType::class, [
                // You can use RecaptchaSubmitType
                // "groups" option is not mandatory
                'constraints' => new Recaptcha2(),
            ])


            ->add('content', CKEditorType::class, array(
             
                'translation_domain' => 'Content',
                'config' => array(
                    'uiColor' => '#ffffff',
                    'height' => '400px',
                    
                    //...
                ),
            ))
           /* ->add('tags', ChoiceType::class, [
                
                      'required' => true,
                     'multiple' => true,
                ])*/
          //  ->add('main_photo')



      
        
        

     
           ->add('submit', SubmitType::class)

            
        ;
        

    }

    public function configureOptions(OptionsResolver $resolver)
    {
        $resolver->setDefaults([
            'data_class' => Posts::class,
            
           
        ]);
    }
}

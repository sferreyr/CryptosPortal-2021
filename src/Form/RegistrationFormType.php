namespace App\Form;

use App\Entity\User;
use Symfony\Component\Form\AbstractType;
use Symfony\Component\Form\Extension\Core\Type\CheckboxType;
use Symfony\Component\Form\Extension\Core\Type\PasswordType;
use Symfony\Component\Form\FormBuilderInterface;
use Symfony\Component\OptionsResolver\OptionsResolver;
use Symfony\Component\Validator\Constraints\IsTrue;
use Symfony\Component\Validator\Constraints\Length;
use Symfony\Component\Validator\Constraints\NotBlank;
use Symfony\Component\Intl\Intl;
use Symfony\Component\Intl\Countries;
use Beelab\Recaptcha2Bundle\Form\Type\RecaptchaType;
use Beelab\Recaptcha2Bundle\Validator\Constraints\Recaptcha2;
use Symfony\Component\Form\Extension\Core\Type\BirthdayType;
use Symfony\Component\Form\Extension\Core\Type\ChoiceType;
use Symfony\Component\Form\Extension\Core\Type\EmailType;

use Symfony\Component\Form\Extension\Core\Type\RepeatedType;

class RegistrationFormType extends AbstractType
{
    public function buildForm(FormBuilderInterface $builder, array $options)
    {
        $countries = Countries::getNames();
        $builder

        ->add('rname', null, [
            'label' => "Real Name",
            'required'   => true,
            'attr' => ['maxlength' => 25,'placeholder' => 'You Real Name']
        ])

        ->add('nickname', null, [
            'label' => "Nickname",
            'required'   => true,
            'attr' => ['maxlength' => 20, 'placeholder' => 'Nickname']
        ])

    
       

        ->add('password', RepeatedType::class, [
            'type' => PasswordType::class,
            'required'   => true,
            'first_options'  => ['label' => 'Password', 'attr' => ['placeholder' => 'Password']],
            'second_options' => ['label' => 'Repeat Password', 'attr' => ['placeholder' => 'Re-Password']],
            'mapped' => false,
            'constraints' => [
                new NotBlank([
                    'message' => 'Please enter a password',
                ]),
                new Length([
                    'min' => 6,
                    'minMessage' => 'Your password should be at least {{ limit }} characters',
                    // max length allowed by Symfony for security reasons
                    'max' => 4096,
                ]),
            ],
        
        ])

        ->add('country', ChoiceType::class, array(
            'choices' => array_flip($countries),
            'label' => 'Country',
            'attr' => ['placeholder' => 'Your Country'],
            'required'   => true,
        ))

        ->add('birthdate', BirthdayType::class, [
            'placeholder' => [
                'year' => 'Year', 'month' => 'Month', 'day' => 'Day',
            ]
        ])

        ->add('captcha', RecaptchaType::class, [
            // You can use RecaptchaSubmitType
            // "groups" option is not mandatory
            'constraints' => new Recaptcha2(),
        ])


            ->add('email', EmailType::class,[
            'attr' => ['maxlength' => 80,'placeholder' => 'You Email']
            ])
            
            ->add('agreeTerms', CheckboxType::class, [
                'label' => ' ',
                'mapped' => false,
                'constraints' => [
                    new IsTrue([
                        'message' => 'You should agree to our terms.',
                    ]),
                ],
            ])
          /*  ->add('plainPassword', PasswordType::class, [
                // instead of being set onto the object directly,
                // this is read and encoded in the controller
                'mapped' => false,
                'constraints' => [
                    new NotBlank([
                        'message' => 'Please enter a password',
                    ]),
                    new Length([
                        'min' => 6,
                        'minMessage' => 'Your password should be at least {{ limit }} characters',
                        // max length allowed by Symfony for security reasons
                        'max' => 4096,
                    ]),
                ],
            ])*/
        ;
    }

    public function configureOptions(OptionsResolver $resolver)
    {
        $resolver->setDefaults([
            'data_class' => User::class,
        ]);
    }
}

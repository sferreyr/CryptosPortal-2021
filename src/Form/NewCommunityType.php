namespace App\Form;

use App\Entity\Categories;
use App\Entity\Communities;
use Beelab\Recaptcha2Bundle\Form\Type\RecaptchaType;
use Symfony\Component\Form\AbstractType;
use Symfony\Component\Validator\Constraints\Image;
use Symfony\Component\Form\FormBuilderInterface;
use Symfony\Component\OptionsResolver\OptionsResolver;
use FOS\CKEditorBundle\Form\Type\CKEditorType;
use Symfony\Component\Form\Extension\Core\Type\FileType;
use Symfony\Component\Form\Extension\Core\Type\TextType;

use Beelab\Recaptcha2Bundle\Validator\Constraints\Recaptcha2;
use Doctrine\ORM\EntityRepository;
use Symfony\Component\Form\Extension\Core\Type\SubmitType;
use Symfony\Bridge\Doctrine\Form\Type\EntityType;

class NewCommunityType extends AbstractType
{
    public function buildForm(FormBuilderInterface $builder, array $options)
    {
        $builder
            ->add('name', TextType::class,array(
                //Label and placeholder read variable from Messages translation.
                'required'   => true,
                'label' => 'NameCommunity',
                'attr' => array(
                    'placeholder' => 'NameCommunity_placeholder'
                    
                ),
            
                


            ))


            ->add('description', CKEditorType::class, array(
             
                'label' => 'NameCommunity_description',
                'config' => array(
                    'uiColor' => '#ffffff',
                    'height' => '400px',
                    
                    //...
                ),
            ))
            ->add('banner', FileType::class, [
                'label' => 'Select Image for Banner',
                 // unmapped means that this field is not associated to any entity property
                 'mapped' => false,
                 'constraints' => [new Image(['maxSize' => '2M', 'mimeTypes' => ['image/jpeg', 'image/png', 'image/gif', 'image/webp']])],

                 // make it optional so you don't have to re-upload the PDF file
                 // every time you edit the Product details
                 'required' => false,
                 
                 ])

           // ->add('cryptoIcon')
            //->add('url')
          
           //  ->add('articles') //In communities constructor
           //->add('reputation') //In communities constructor
            //   ->add('createAt') //In communities constructor

       

            ->add('categories', EntityType::class, [
                'class' => Categories::class,
                'query_builder' => function (EntityRepository $er) {
                    return $er->createQueryBuilder('u')
                        ->orderBy('u.name', 'ASC');
                },
                'choice_label' => 'name',
                'choice_value' => 'name',
            ])

            //  ->add('owner')

            ->add('captcha', RecaptchaType::class, [
                // You can use RecaptchaSubmitType
                // "groups" option is not mandatory
                'constraints' => new Recaptcha2(),
            ])


            ->add('submit', SubmitType::class)
            

            ;


    }

    public function configureOptions(OptionsResolver $resolver)
    {
        $resolver->setDefaults([
            'data_class' => Communities::class,
        ]);
    }
}

function check($condition, $message) {
    if (!$condition) {
        throw new RuntimeException($message);
    }
    echo "PASS: $message\n";
}
function rejects(callable $action, string $exception, string $message) {
    try { $action(); } catch (Throwable $error) {
        if (!$error instanceof $exception) {
            throw new RuntimeException($message . ': ' . get_class($error) . ' ' . $error->getMessage(), 0, $error);
        }
        check(true, $message);
        return;
    }
    throw new RuntimeException($message);
}
function withId($object, int $id) {
    $property = new ReflectionProperty(get_class($object), 'id');
    $property->setAccessible(true);
    $property->setValue($object, $id);
    return $object;
}


class MemoryManager {
    public $repositories = [];
    public $users = [];
    public $posts = [];
    public $writes = 0;
    public function getRepository($class) {
        return $this->repositories[$class] ?? ($this->repositories[$class] = new MemoryRepository());
    }
    public function transactional($action) { return $action($this); }

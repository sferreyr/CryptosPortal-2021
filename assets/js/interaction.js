document.getElementById('Like').onclick = function() {

    var ruta = Routing.generate('likes');
    var postId = $('#Like').data("isLike"); // Data is (COMIENZA EN MAYUSCULA )
    //  alert(postId); //Data obtenida

    $.ajax({
        type: 'POST',
            headers: { 'X-CSRF-Token': document.querySelector('meta[name="csrf-token"]').content },
        url: ruta,
        data: ({ id: postId }),
        async: true,
        dataType: "json",
        success: function(data) {
            console.log(data['likes']);
            if ((data['likes']) == 'AlreadyLike') {
                $(".toast-body").replaceWith(" <div class='toast-body'>" + 'You alredy Liked this' + "</div>");
                $('.toast').toast('show');
                //Prevent Double click
                $("#Like").on("click", function() {
                    $(this).attr("disabled", "disabled");

                });

            } else {
                $(".totallikes").replaceWith("  <small class='totallikes'>" + data['likes'] + "</small>  ");
                //Prevent Double click
                $("#Like").on("click", function() {
                    $(this).attr("disabled", "disabled");

                });

            }

        }
    })

};


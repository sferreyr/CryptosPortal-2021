//CryptoFormat
function formatCryptoData(crypto) {
    if (!crypto.id) {
        return crypto.text;
    }
    /*\img\cryptos\btc.png*/
    var baseUrl = "./img/cryptos";
    var $crypto = $(
        '<span><img style="max-width:16px" src="' + baseUrl + '/' + crypto.text.toLowerCase() + '.png" class="img-crypto" /> ' + crypto.text + '</span>'
    );
    return $crypto;
};

//TopicFormat
function formatTopicData(topic) {
    if (!topic.id) {
        return topic.text;
    }
    /*\img\cryptos\btc.png*/
    var baseUrl = "./img/misc/subcategory";
    var $topic = $(
        '<span><img style="max-width:16px" src="' + baseUrl + '/' + topic.text + '.png" class="img-topic" /> ' + topic.text + '</span>'
    );
    return $topic;
};




//Categories((Cryptos))
$('#categories_name').select2({
    width: '100%',
    placeholder: "Select an Option",
    allowClear: true,
    templateResult: formatCryptoData,
    templateSelection: formatCryptoData
})


$(function() {
    var selected = localStorage.getItem('selected');
    if (selected) {
        $("#categories_name").val(selected);
        // Si se selecciona.
    }

    $("#categories_name").change(function() {
        localStorage.setItem('selected', $(this).val());

        // var ruta = Routing.generate('FilterCC'); NEED options={"expose"=true} controller

        var ruta = './MainboardFilterCryptoCategory'

        //Ajax Function to send a get request
        $.ajax({
            type: "POST",
            url: ruta,
            data: {
                "catid": "1"
            },
            dataType: "json",
            success: function(data) {
                console.log(data)
                var userselected = $("#categories_name :selected").text();

                var rutaFinal = '../public/dashboard?filterField=c.name&filterValue=' + userselected;
                // $('.latestpost').replaceWith('<div class="region">' + data + '</div>');
                //alert($("#categories_name :selected").text());
                location.href = rutaFinal;
            }

        });

    });


});



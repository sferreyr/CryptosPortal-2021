import '../css/messages.scss';

//Delete Notifications
$(function() {

    $("#showToast").click(function() {
        $('.toast').toast('show');
    });


    $('.DelMessage').on('click', function(e) { //AL HACER CLICK EN EL
        var ruta = Routing.generate('my_MessageDEL');
        var MessageID = $(this).data("isLike"); // Data is (COMIENZA EN MAYUSCULA ) BUSCA EL BOTON CON ESE ID
        //alert(MessageID); //Data obtenida
        var MessagesCount = $('.messages').attr("data-count");
        MessagesCount = MessagesCount - 1;


        $.ajax({
            type: 'POST',
            headers: { 'X-CSRF-Token': document.querySelector('meta[name="csrf-token"]').content },
            url: ruta,
            data: ({
                id: MessageID
            }),
            async: true,
            dataType: "json",
            success: function(data) {
                console.log(data['notification']);
                // Remove <div> with id
                $("#" + MessageID).remove();
                //Profile Nav
                $(".MessagesCountitem").replaceWith("<span class='MessagesCountitem'>" + MessagesCount + "</span>");
                //Nav
                $(".messages").replaceWith("<span class='messages fa-stack fa-1x' data-count=" + MessagesCount + ">" + "<i class='fa fa-envelope fa-stack-1x fa-inverse'></i>");

                $('.toast').toast('show');




            }
        })

    });
});



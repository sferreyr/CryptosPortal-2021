//Delete Notifications
$(function() {

    $("#showToast").click(function() {
        $('.toast').toast('show');
    });


    $('.notification').on('click', function(e) { //AL HACER CLICK EN EL
        var ruta = Routing.generate('my_profileNDEL');
        var notificationID = $(this).data("isLike"); // Data is (COMIENZA EN MAYUSCULA ) BUSCA EL BOTON CON ESE ID
        // alert(notificationID); //Data obtenida
        //  var notificationCount = $(".notificationCount").text();
        var notificationCount = $('.notifications').attr("data-count");
        notificationCount = notificationCount - 1;

        $.ajax({
            type: 'POST',
            headers: { 'X-CSRF-Token': document.querySelector('meta[name="csrf-token"]').content },
            url: ruta,
            data: ({ id: notificationID }),
            async: true,
            dataType: "json",
            success: function(data) {
                console.log(data['notification']);
                // Remove <div> with id
                $("#" + notificationID).remove();
                $(".notifications").replaceWith("<span class='notifications fa-stack fa-1x' data-count=" + notificationCount + ">" + "<i class='fa fa-bell fa-stack-1x fa-inverse'></i> </span>");

                $(".Notilength").replaceWith(" <p class='Notilength'> Do you have " + notificationCount + " Notifications </p> ");
                $('.toast').toast('show');




            }
        })

    });
});